CREATE TABLE b_bloodknight_lead (
    ID INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    CODE CHAR(25) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    RESULT_ID INT UNSIGNED NOT NULL,
    WEBFORM_ID INT UNSIGNED NOT NULL,
    DATE_CREATED DATETIME NOT NULL,
    STATUS_ID TINYINT UNSIGNED NOT NULL DEFAULT 0,
    IP VARCHAR(45) NOT NULL DEFAULT '',
    UNIQUE KEY ux_code (CODE),
    UNIQUE KEY ux_result (RESULT_ID),
    KEY ix_overdue (STATUS_ID, DATE_CREATED)
) ENGINE=InnoDB
